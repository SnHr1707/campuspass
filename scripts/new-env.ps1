<#
.SYNOPSIS
  Creates a .env file with strong random secrets for CampusPass.

.DESCRIPTION
  The .env file is git-ignored. It is used by docker compose locally, and by
  scripts\bootstrap.ps1 to create the Kubernetes Secret on the cloud cluster.

.EXAMPLE
  .\scripts\new-env.ps1
#>
param(
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$envPath = Join-Path $PSScriptRoot '..\.env'

if ((Test-Path $envPath) -and -not $Force) {
    Write-Host ".env already exists. Use -Force to replace it (existing data will need the old passwords)." -ForegroundColor Yellow
    exit 1
}

function New-Secret([int]$Bytes = 24) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($buffer)
    $rng.Dispose()
    return -join ($buffer | ForEach-Object { $_.ToString('x2') })
}

$organiserCode = 'ORG-' + (New-Secret 3).ToUpper()
$volunteerCode = 'VOL-' + (New-Secret 3).ToUpper()

$content = @"
# Generated by scripts/new-env.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). Keep this file private.
POSTGRES_PASSWORD=$(New-Secret)
AUTH_DB_PASSWORD=$(New-Secret)
BOOKING_DB_PASSWORD=$(New-Secret)
TICKET_DB_PASSWORD=$(New-Secret)
JWT_SECRET=$(New-Secret 32)
TICKET_SIGNING_SECRET=$(New-Secret 32)
ORGANISER_INVITE_CODE=$organiserCode
VOLUNTEER_INVITE_CODE=$volunteerCode
"@

Set-Content -Path $envPath -Value $content -Encoding ascii
Write-Host "Created .env with new random secrets." -ForegroundColor Green
Write-Host "Organiser invite code: $organiserCode"
Write-Host "Volunteer invite code: $volunteerCode"
Write-Host "Share these codes only with organisers and volunteers."
